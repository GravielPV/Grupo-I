import test from 'node:test';
import assert from 'node:assert/strict';
import { once } from 'node:events';
import { MongoMemoryReplSet } from 'mongodb-memory-server';
import { openMongoDatabase } from '../src/mongo-store.js';
import { createApp } from '../src/app.js';
import { hashPassword } from '../src/security.js';

test('network: shared codes, independent inventory/cash, uploaded photos, simulated card and refunds', async t => {
  const repl = await MongoMemoryReplSet.create({ replSet: { count: 1 } }); t.after(() => repl.stop());
  const config = { mongoUri: repl.getUri(), mongoDatabase: 'pharmacy_network_test' };
  let store = await openMongoDatabase(config); t.after(() => store.close());
  const hash = await hashPassword('test-password');
  await store.insertUser('Admin', 'admin', hash, 'admin'); await store.insertUser('Employee', 'employee', hash, 'employee');
  // Simular los datos anteriores a esta ampliación y comprobar la migración idempotente.
  const legacy = await store.insertProduct('Artículo previo', 'General', 100, 3, '2099-01-01');
  await store.close(); store = await openMongoDatabase(config);
  const migrated = await store.productById(legacy.lastInsertRowid);
  assert.equal(migrated.code, 'ART-000001'); assert.equal(migrated.pharmacyId, 1); assert.equal(migrated.stock, 3);
  const server = (await createApp({ store })).listen(0, '127.0.0.1'); await once(server, 'listening');
  t.after(() => new Promise(resolve => server.close(resolve)));
  const base = `http://127.0.0.1:${server.address().port}/api`;
  let admin;
  async function request(path, method = 'GET', body, pharmacyId = 1, token = admin) {
    const response = await fetch(base + path, { method, headers: { 'Content-Type': 'application/json', 'X-Pharmacy-Id': String(pharmacyId), ...(token ? { Authorization: `Bearer ${token}` } : {}) }, body: body === undefined ? undefined : JSON.stringify(body) });
    return { status: response.status, body: response.status === 204 ? null : await response.json() };
  }
  const expect = (response, status) => { assert.equal(response.status, status, JSON.stringify(response.body)); return response.body; };
  admin = expect(await request('/auth/login', 'POST', { username: 'admin', password: 'test-password' }), 200).token;
  const employee = expect(await request('/auth/login', 'POST', { username: 'employee', password: 'test-password' }), 200).token;
  const second = expect(await request('/pharmacies', 'POST', { name: 'Farmacia Norte', address: 'Calle de prueba', phone: '000' }), 201);
  expect(await request('/pharmacies', 'POST', { name: 'farmacia norte' }), 409);
  expect(await request('/pharmacies', 'POST', { name: 'Sin permiso' }, 1, employee), 403);
  assert.equal(expect(await request('/pharmacies'), 200).length, 2);
  expect(await request('/products', 'GET', undefined, 999), 400);

  const location = expect(await request('/locations', 'POST', { section: 'A', shelf: '1', level: '2' }), 201);
  assert.deepEqual(expect(await request('/locations', 'GET', undefined, second.id), 200), []);
  expect(await request(`/locations/${location.id}`, 'PUT', { section: 'B', shelf: '1', level: '2' }, second.id), 404);
  const productData = { name: 'Medicina compartida', category: 'General', code: 'MED-001', price: 12.35, stock: 8, expirationDate: '2099-01-01' };
  const a = expect(await request('/products', 'POST', { ...productData, location: location._id }), 201);
  expect(await request('/products', 'POST', productData), 409);
  expect(await request('/products', 'POST', { ...productData, location: location._id }, second.id), 400);
  expect(await request('/products', 'POST', { ...productData, name: 'Artículo diferente' }, second.id), 409);
  const b = expect(await request('/products', 'POST', { ...productData, stock: 5 }, second.id), 201);
  assert.notEqual(a.id, b.id); assert.equal(a.code, b.code);
  assert.equal(expect(await request('/products', 'GET', undefined, second.id), 200).length, 1);
  expect(await request(`/products/${a.id}`, 'GET', undefined, second.id), 404);
  expect(await request(`/products/${a.id}`, 'DELETE', undefined, second.id), 404);
  expect(await request(`/products/${b.id}`, 'PUT', { ...productData, stock: 5, code: 'OTHER' }, second.id), 400);
  expect(await request(`/batches/product/${a.id}`, 'GET', undefined, second.id), 404);
  expect(await request('/movements', 'POST', { product: a._id, type: 'salida', quantity: 1, reason: 'Otra farmacia' }, second.id), 404);
  let availability = expect(await request('/availability?search=med-001', 'GET', undefined, second.id, employee), 200);
  assert.deepEqual(availability.articles[0].pharmacies.map(p => p.availableStock).sort((x, y) => x - y), [5, 8]);

  const photo = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+a6mgAAAAASUVORK5CYII=', 'base64');
  const upload = await fetch(base + '/images', { method: 'POST', headers: { Authorization: `Bearer ${admin}`, 'Content-Type': 'image/png' }, body: photo });
  assert.equal(upload.status, 201); const { imageUrl } = await upload.json();
  const downloaded = await fetch(new URL(imageUrl, base));
  assert.equal(downloaded.headers.get('content-type'), 'image/png'); assert.deepEqual(Buffer.from(await downloaded.arrayBuffer()), photo);
  const invalid = await fetch(base + '/images', { method: 'POST', headers: { Authorization: `Bearer ${admin}`, 'Content-Type': 'image/png' }, body: 'not a picture' });
  assert.equal(invalid.status, 400);
  const unauthorized = await fetch(base + '/images', { method: 'POST', headers: { Authorization: `Bearer ${employee}`, 'Content-Type': 'image/png' }, body: photo });
  assert.equal(unauthorized.status, 403);
  expect(await request(`/products/${a.id}`, 'PUT', { ...productData, imageUrl }), 200);
  assert.equal((await request(`/products/${a.id}`)).body.imageUrl, imageUrl);
  expect(await request(`/products/${a.id}`, 'PUT', { ...productData, imageUrl: 'javascript:alert(1)' }), 400);

  expect(await request('/cash-sessions/open', 'POST', { openingAmount: 100 }), 201);
  expect(await request('/cash-sessions/open', 'POST', { openingAmount: 50 }, second.id), 201);
  const settings = (await request('/settings')).body;
  expect(await request('/settings', 'PUT', { ...settings, pharmacyName: 'Nombre independiente' }, second.id), 200);
  assert.equal((await request('/settings')).body.pharmacyName, 'Tu Pharmacy');
  assert.equal((await request('/settings', 'GET', undefined, second.id)).body.pharmacyName, 'Nombre independiente');
  const cart = { items: [{ product: b._id, quantity: 2 }] };
  const cardSale = { ...cart, paymentMethod: 'card' };
  expect(await request('/sales', 'POST', cardSale, second.id), 400);
  const declined = expect(await request('/card-payments', 'POST', { ...cart, testCard: 'declined' }, second.id), 402);
  assert.equal(declined.status, 'declined'); assert.equal(declined.simulated, true);
  expect(await request('/sales', 'POST', { ...cardSale, paymentId: declined.id }, second.id), 409);
  expect(await request('/card-payments', 'POST', { ...cart, testCard: 'approved', cardNumber: '4242424242424242' }, second.id), 400);
  const approved = expect(await request('/card-payments', 'POST', { ...cart, testCard: 'approved' }, second.id), 201);
  assert.equal(approved.amount, 24.7); assert.equal(approved.last4, '4242'); assert.ok(approved.authorizationCode);
  expect(await request('/sales', 'POST', { ...cardSale, paymentId: approved.id }, 1), 404);
  expect(await request('/sales', 'POST', { ...cardSale, paymentId: approved.id }, second.id, employee), 409);
  expect(await request('/sales', 'POST', { ...cardSale, items: [{ product: b._id, quantity: 1 }], paymentId: approved.id }, second.id), 409);
  assert.equal((await store.productById(b.id)).stock, 5);
  const attempts = await Promise.all([request('/sales', 'POST', { ...cardSale, paymentId: approved.id }, second.id), request('/sales', 'POST', { ...cardSale, paymentId: approved.id }, second.id)]);
  assert.deepEqual(attempts.map(r => r.status).sort(), [201, 409]);
  const sale = attempts.find(r => r.status === 201).body;
  assert.equal(sale.payment.reference, approved.reference); assert.equal(sale.items[0].productCode, 'MED-001');
  assert.equal((await store.productById(b.id)).stock, 3); assert.equal((await store.productById(a.id)).stock, 8);
  assert.equal((await request('/sales')).body.length, 0);
  assert.equal((await request('/movements')).body.length, 0);
  assert.equal((await request('/cash-sessions/current', 'GET', undefined, second.id)).body.summary.cardSales, 24.7);

  const returnBody = { saleId: sale._id, items: [{ productId: b._id, quantity: 1 }], reason: 'Devolución de prueba', refundMethod: 'card' };
  expect(await request('/returns', 'POST', returnBody), 404);
  const returned = expect(await request('/returns', 'POST', returnBody, second.id), 201);
  assert.match(returned.refundReference, /^DEMO-REFUND-/); assert.equal(returned.total, 12.35);
  assert.equal((await store.productById(b.id)).stock, 4);
  assert.equal((await request('/returns')).body.length, 0);
  expect(await request('/returns', 'POST', { ...returnBody, items: [{ productId: b._id, quantity: 2 }] }, second.id), 409);
  const summary = (await request('/cash-sessions/current', 'GET', undefined, second.id)).body.summary;
  assert.equal(summary.cardRefunds, 12.35); assert.equal(summary.expectedCash, 50);
  availability = (await request('/availability?search=MED-001')).body;
  assert.deepEqual(availability.articles[0].pharmacies.map(p => p.availableStock).sort((x, y) => x - y), [4, 8]);
  await request('/cash-sessions/close', 'POST', { countedCash: 50 }, second.id);
  assert.equal((await request('/cash-sessions/current', 'GET', undefined, second.id)).body, null);
  assert.equal((await request('/cash-sessions/current')).body.status, 'open');

  // Una autorización caducada no descuenta inventario; anular revierte un pago demo.
  await request('/cash-sessions/open', 'POST', { openingAmount: 0 }, second.id);
  const expiring = expect(await request('/card-payments', 'POST', { ...cart, testCard: 'approved' }, second.id), 201);
  await store.updateRecord('card_payments', expiring.id, { expiresAt: Date.now() - 1 });
  expect(await request('/sales', 'POST', { ...cardSale, paymentId: expiring.id }, second.id), 409);
  assert.equal((await store.productById(b.id)).stock, 4);
  const next = expect(await request('/card-payments', 'POST', { ...cart, testCard: 'approved' }, second.id), 201);
  const reversible = expect(await request('/sales', 'POST', { ...cardSale, paymentId: next.id }, second.id), 201);
  const reversed = expect(await request(`/sales/${reversible.id}/cancel`, 'PATCH', undefined, second.id), 200);
  assert.equal(reversed.payment.status, 'voided'); assert.match(reversed.payment.voidReference, /^DEMO-VOID-/);
  assert.equal((await store.productById(b.id)).stock, 4);
  assert.equal(JSON.stringify(await store.listRecords('card_payments')).includes('4242424242424242'), false);
  const productBatches = (await request(`/batches/product/${b.id}`, 'GET', undefined, second.id)).body;
  await store.updateRecord('batches', productBatches[0].id, { expirationDate: '2000-01-01' });
  const expired = (await request(`/products/${b.id}`, 'GET', undefined, second.id)).body;
  assert.equal(expired.stock, 4); assert.equal(expired.availableStock, 0); assert.equal(expired.availableForSale, false);
  availability = (await request('/availability?search=MED-001')).body;
  assert.equal(availability.articles[0].pharmacies.find(p => p.id === second.id).available, false);
});
